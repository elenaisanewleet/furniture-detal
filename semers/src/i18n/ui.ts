const DICTS: Record<Locale, Partialised> = { en, ru, lv };

/** One level of merge is enough: the dictionary is flat apart from the four label groups. */
function merge(locale: Locale): Dict {
  if (locale === DEFAULT_LOCALE) return en;
  const over = DICTS[locale] || {};
  const out: Record<string, unknown> = { ...en };
  for (const [k, v] of Object.entries(over)) {
    if (v === undefined) continue;
    const base = (en as Record<string, unknown>)[k];
    out[k] = base && typeof base === 'object' && !Array.isArray(base) && typeof v === 'object' && !Array.isArray(v) ? { ...(base as object), ...(v as object) } : v;
  }
  return out as Dict;
}

const CACHE = new Map<Locale, Dict>();

/** Dictionary for a locale, with English filling any gap. */
export function t(locale: Locale): Dict {
  let d = CACHE.get(locale);
  if (!d) CACHE.set(locale, (d = merge(locale)));
  return d;
}

/**
 * The few strings above carry **bold** because they mix emphasis into a
 * sentence a translator has to be able to reorder. Rendered with set:html after
 * escaping, so a dictionary is the only thing that can introduce markup.
 */
export function bold(sTr: string): string {
  const esc = sTr.replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' })[c] as string);
  return esc.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
}

/** Substitute {placeholders} in a runtime template. */
export function fill(tpl: string, vars: Record<string, string | number>): string {
  return tpl.replace(/\{(\w+)\}/g, (_m, k) => String(vars[k] ?? ''));
}

