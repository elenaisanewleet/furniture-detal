/**
 * Шесть страниц услуг.
 *
 * Структура у них общая — хиро, «что входит», станки, заявка, вопросы,
 * перелинковка, — поэтому шаблон один, а различается только то, что лежит
 * здесь. Копирайт окончательный: он согласован и воспроизводится дословно.
 *
 * Каждая страница — под свой кластер запросов; отсюда отдельные title,
 * description и keywords, а не общий шаблон с подстановкой названия.
 */

export interface Faq {
  q: string;
  a: string;
}

export interface Service {
  /** Он же адрес: /<slug>/ */
  slug: string;
  /** Короткое имя — меню, подвал, хлебные крошки, перелинковка. */
  label: string;
  /** Заголовок страницы. */
  h1: string;
  /** Слово в заголовке, которое несёт сигнальный цвет. Может отсутствовать. */
  h1em?: string;
  title: string;
  description: string;
  keywords: string;
  lead: string;
  /** Что входит в услугу. */
  includes: string[];
  /** Якоря на станки, на которых идёт эта работа. */
  machines: string[];
  faq: Faq[];
  /** Название и тип для schema.org Service. */
  schemaName: string;
  serviceType: string;
  /** Что подставляется в скрытое поле темы заявки. */
  topic: string;
  /** Три ссылки в блоке «Другие работы». */
  related: string[];
  /** Номер карточки в хабе на главной и её текст. */
  hubNo: string;
  hubText: string;
}

